#!/usr/bin/env node
/**
 * Bundles the board's TypeScript logic for the native iPad app (docs/IPAD-NATIVE.md, "The brain").
 *
 *   npm run brain:build            writes ios/Packages/AgathonBrain/Sources/AgathonBrain/Resources/brain.js
 *   npm run brain:check            fails when the committed brain.js is not what the sources build
 *   node scripts/build-ios-brain.mjs --report    also prints what the bundle is made of
 *
 * One minified IIFE, `var AgathonBrain = …` (a global in JavaScriptCore), from `src/lib/brain/index.ts`.
 * The built file is committed so Xcode builds without node. The target is what JavaScriptCore on
 * iOS 17 runs (Safari 17's engine), so nothing is down-levelled that it already has.
 *
 * Guards: `tldraw` resolves to a shim that throws (`src/lib/brain/shims/tldraw.ts`) and the build
 * fails if the shim, React, `process.env` or `require(` survive tree-shaking, since plain
 * JavaScriptCore has none of them.
 */
import { build } from "esbuild";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import zlib from "node:zlib";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "ios/Packages/AgathonBrain/Sources/AgathonBrain/Resources/brain.js");
const ENTRY = path.join(root, "src/lib/brain/index.ts");
const SHIM = path.join(root, "src/lib/brain/shims/tldraw.ts");

/** What plain JavaScriptCore lacks: none of it may be left in the bundle. */
const FORBIDDEN = [
  { re: /AGATHON_BRAIN_TLDRAW_SHIM/, why: "a tldraw call is reachable from the brain API" },
  { re: /process\.env/, why: "process.env survived (add it to `define`)" },
  { re: /\brequire\(/, why: "a CommonJS require survived" },
  { re: /react\.(production|development)/i, why: "React was bundled" },
];

/**
 * `mathjs` as only what the engine uses: `create`, the factories (`all`) and `version`. The package's
 * main entry also builds mathjs's default instance when it loads (its impure functions are not
 * marked pure, so nothing tree-shakes them): a second instance the brain never uses, paid for in
 * size and in JavaScriptCore's cold start. Deep files are imported by path (the package's `exports`
 * map hides them); `create(all)` is the same instance either way.
 */
const MATHJS_ESM = path.join(root, "node_modules/mathjs/lib/esm");
const mathjsFactoriesOnly = {
  name: "mathjs-factories-only",
  setup(b) {
    b.onResolve({ filter: /^mathjs$/ }, () => ({ path: "mathjs", namespace: "agathon-mathjs" }));
    b.onLoad({ filter: /.*/, namespace: "agathon-mathjs" }, () => ({
      loader: "js",
      resolveDir: root,
      contents: [
        `export { create } from ${JSON.stringify(path.join(MATHJS_ESM, "core/create.js"))};`,
        `export { all } from ${JSON.stringify(path.join(MATHJS_ESM, "entry/allFactoriesAny.js"))};`,
        `export { version } from ${JSON.stringify(path.join(MATHJS_ESM, "version.js"))};`,
      ].join("\n"),
    }));
  },
};

export async function buildBrain({ write = true } = {}) {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    outfile: OUT,
    format: "iife",
    globalName: "AgathonBrain",
    platform: "neutral",
    mainFields: ["module", "main"],
    conditions: ["import", "default"],
    target: ["safari17"],
    minify: true,
    treeShaking: true,
    legalComments: "eof",
    charset: "utf8",
    metafile: true,
    tsconfig: path.join(root, "tsconfig.json"),
    alias: { tldraw: SHIM },
    plugins: [mathjsFactoriesOnly],
    define: {
      "process.env.NODE_ENV": '"production"',
      "process.env.NEXT_PUBLIC_LIVE_MATH": "undefined",
    },
    banner: { js: "/* Agathon brain for the iPad app. Generated by scripts/build-ios-brain.mjs from src/lib/brain; do not edit. */" },
    logLevel: "silent",
  });
  const out = result.outputFiles.find((f) => f.path.endsWith("brain.js"));
  if (!out) throw new Error("esbuild wrote no brain.js");
  const code = out.text;
  const problems = FORBIDDEN.filter((f) => f.re.test(code)).map((f) => f.why);
  if (problems.length > 0) throw new Error(`brain.js cannot run in JavaScriptCore:\n  - ${problems.join("\n  - ")}`);
  if (write) {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, code);
  }
  return { code, metafile: result.metafile };
}

/** Bytes in the output by npm package, or by `src/lib/<area>` for our own code. */
export function composition(metafile) {
  const output = Object.values(metafile.outputs)[0];
  const groups = new Map();
  for (const [file, info] of Object.entries(output.inputs)) {
    const pkg = /node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(file)?.[1];
    const own = /^src\/lib\/([^/]+(?:\/[^/.]+)?)/.exec(file)?.[1];
    const key = pkg ? `npm:${pkg}` : own ? `src/lib/${own.replace(/\/[^/]+\.tsx?$/, "")}` : file;
    groups.set(key, (groups.get(key) ?? 0) + info.bytesInOutput);
  }
  return [...groups].sort((a, b) => b[1] - a[1]);
}

function kb(n) {
  return `${(n / 1024).toFixed(1)} KB`;
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const check = args.has("--check");
  const { code, metafile } = await buildBrain({ write: !check });
  const bytes = Buffer.byteLength(code);
  const gz = zlib.gzipSync(code, { level: 9 }).length;
  const sha = createHash("sha256").update(code).digest("hex").slice(0, 12);
  if (check) {
    const committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (committed !== code) {
      console.error(`brain.js is stale: the sources build ${kb(bytes)} (sha ${sha}), the committed file differs. Run \`npm run brain:build\` and commit it.`);
      process.exit(1);
    }
    console.log(`brain.js is current (${kb(bytes)}, gzip ${kb(gz)}, sha ${sha})`);
    return;
  }
  console.log(`wrote ${path.relative(root, OUT)}: ${kb(bytes)} minified, ${kb(gz)} gzip, sha ${sha}`);
  if (args.has("--report")) {
    for (const [name, n] of composition(metafile).slice(0, 25)) console.log(`  ${kb(n).padStart(10)}  ${((100 * n) / bytes).toFixed(1).padStart(5)}%  ${name}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(e.message ?? e);
    process.exit(1);
  });
}
