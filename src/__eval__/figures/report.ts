/**
 * docs/eval/figures.md: the figure eval's scoreboard (see ./run.ts). The recommendation between the
 * `<!-- recommendation:start -->` / `<!-- recommendation:end -->` markers is written by hand and kept
 * when the report is generated again.
 */
import type { SpendState } from "../models/client";
import type { FigureCase } from "./corpus";
import type { FigureResult } from "./run";

export interface FigureReportInput {
  corpus: readonly FigureCase[];
  results: readonly FigureResult[];
  spend: SpendState;
  spentThisRun: number;
  date: string;
  catalogFetchedAt: string;
  previous?: string;
}

export function percentile(values: readonly number[], p: number): number {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.max(0, Math.ceil((p / 100) * sorted.length) - 1))];
}

const row = (cells: readonly string[]) => `| ${cells.join(" | ")} |`;
const table = (head: readonly string[], rows: readonly (readonly string[])[]) => [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");
const usd = (v: number) => `$${v.toFixed(v < 0.01 ? 5 : 4)}`;
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function label(r: Pick<FigureResult, "model" | "prompt">): string {
  return r.prompt === "baseline" ? `${r.model} (before: free-form lines)` : r.model;
}

export function renderFiguresMarkdown(input: FigureReportInput): string {
  const { corpus, results } = input;
  const runs = [...new Set(results.map(label))];
  const byRun = (name: string) => results.filter((r) => label(r) === name);
  const n = corpus.length;
  const configs = [...new Set(corpus.map((f) => f.config))];

  const summary = runs.map((name) => {
    const rs = byRun(name);
    const correct = rs.filter((r) => r.written === "correct").length;
    const wrong = rs.filter((r) => r.written === "wrong").length;
    const nothing = rs.filter((r) => r.written === "nothing").length;
    const structured = rs[0]?.prompt === "structured";
    const facts = rs.filter((r) => r.source === "facts" && r.written !== "nothing").length;
    const factsRight = rs.filter((r) => r.factsCorrect).length;
    const fb = rs.filter((r) => r.source === "lines" && r.written !== "nothing");
    const lat = rs.filter((r) => r.call.ok).map((r) => r.call.latencyMs);
    const cost = rs.reduce((s, r) => s + r.call.costUsd, 0);
    return [
      structured ? `\`${name}\`` : `\`${rs[0]?.model}\` — before (free-form lines)`,
      `**${correct}** / ${n}`,
      wrong > 0 ? `**${wrong}**` : "0",
      String(nothing),
      structured ? `${facts} (${factsRight} right on their own)` : "—",
      structured ? `${fb.length} → ${fb.filter((r) => r.written === "correct").length} right` : "—",
      `${(percentile(lat, 50) / 1000).toFixed(1)} s`,
      `${(percentile(lat, 95) / 1000).toFixed(1)} s`,
      usd(cost / Math.max(1, rs.length)),
      usd(cost),
    ];
  });

  const byConfig = configs.map((c) => {
    const ids = corpus.filter((f) => f.config === c).map((f) => f.id);
    return [
      c,
      String(ids.length),
      ...runs.map((name) => {
        const rs = byRun(name).filter((r) => ids.includes(r.figure));
        const ok = rs.filter((r) => r.written === "correct").length;
        const wrong = rs.filter((r) => r.written === "wrong").length;
        return `${ok}/${ids.length}${wrong > 0 ? ` (**${wrong} wrong**)` : ""}`;
      }),
    ];
  });

  const wrongRows = results
    .filter((r) => r.written === "wrong")
    .map((r) => [label(r), r.figure, r.value === null ? "—" : String(Number(r.value.toFixed(3))), String(Number(r.expected.toFixed(3))), r.source, esc(r.reason || "")]);
  const refused = results
    .filter((r) => r.prompt === "structured" && r.written !== "wrong" && r.reason)
    .map((r) => [r.model, r.figure, r.written, esc(r.reason).slice(0, 140)]);

  const previous = input.previous ?? "";
  const rec = /<!-- recommendation:start -->[\s\S]*?<!-- recommendation:end -->/.exec(previous)?.[0] ?? "<!-- recommendation:start -->\n(The pick, written by hand after a run.)\n<!-- recommendation:end -->";

  const models = Object.entries(input.spend.byModel).map(([m, s]) => [m, String(s.calls), usd(s.usd)]);
  return [
    "# Figure eval: the tutor reads a hand-drawn figure",
    "",
    `> Generated by \`npm run eval:figures\` (src/__eval__/figures/figures.test.ts; real model calls, gated by RUN_FIGURE_EVAL=1) on ${input.date}; OpenRouter catalog of ${input.catalogFetchedAt}.`,
    `> ${n} figures (src/__eval__/figures/corpus.ts) drawn as strokes by the corpus pen — lines, angle arcs, right-angle boxes, tick marks, arrow marks — with labels in a student's hand, rendered as the board's crop (white, 3.5 px ink, ≤ 768 px wide) and sent with their labels as the recognizer reads them when it reads them right.`,
    "> Each reply goes through the production prompt and route logic (`figureSetup`: the model's structured read planned into equations by `planFigure`, else its own lines) and the board's decision (`figureAnswer`: the engine solves it and the answer is checked).",
    "> **Wrong** is a wrong answer written on the student's page; **nothing** means the board writes nothing (asked: \"Couldn't work this out\"; unasked: silence).",
    "",
    "## Summary",
    "",
    table(["model", "correct", "wrong", "nothing", "read used", "fallback lines used", "p50", "p95", "cost / figure", "cost"], summary),
    "",
    rec,
    "",
    "## By configuration",
    "",
    table(["configuration", "figures", ...runs.map((r) => `\`${r}\``)], byConfig),
    "",
    "## Wrong answers written",
    "",
    wrongRows.length === 0 ? "None." : table(["run", "figure", "written", "expected", "from", "note"], wrongRows),
    "",
    "## Why a read was not used (structured prompt)",
    "",
    refused.length === 0 ? "Every read was used." : table(["model", "figure", "written", "reason"], refused.slice(0, 80)),
    "",
    "## Spend",
    "",
    `This run: ${usd(input.spentThisRun)} (new calls only; cached replies cost nothing). Total on the figure ledger: ${usd(input.spend.totalUsd)} over ${input.spend.calls} calls (cap $0.90).`,
    "",
    table(["model", "calls", "spent"], models),
    "",
  ].join("\n");
}
