/** Multi-character atlas keys that must be matched before single characters. */
export const LIGATURES = ["d/dx"] as const;

/** Frequent letters that must have 2–3 alternates. */
export const COMMON_LETTERS = "etaoinshrdlucm";

const ALIASES: Record<string, string> = {
  "—": "-",
  "*": "×",
};

export function glyphKey(ch: string): string {
  if (ATLAS[ch]) return ch;
  if (ALIASES[ch] && ATLAS[ALIASES[ch]]) return ALIASES[ch];
  const lower = ch.toLowerCase();
  if (ATLAS[lower]) return lower;
  return ch;
}

export function hasGlyph(ch: string): boolean {
  return Boolean(ATLAS[glyphKey(ch)]);
}

export function tokenizeHand(text: string): string[] {
  const out: string[] = [];
  let i = 0;
  while (i < text.length) {
    const lig = LIGATURES.find((item) => text.startsWith(item, i));
    if (lig) {
      out.push(lig);
      i += lig.length;
      continue;
    }
    out.push(text[i]);
    i += 1;
  }
  return out;
}
